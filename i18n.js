const SUPPORTED_LANGS = Object.keys(translations);

export function detectInitialLanguage() {
    const raw = (navigator.language || (navigator.languages && navigator.languages[0]) || "bg").toLowerCase();
    const shortCode = raw.split("-")[0];
    if (shortCode === "zh") return "zh";
    return SUPPORTED_LANGS.includes(shortCode) ? shortCode : "bg";
}

export function getTranslation(lang, key) {
    const dict = translations[lang] || translations.bg;
    return dict[key] ?? translations.bg[key] ?? key;
}

export function applyTranslationsToDom(lang) {
    const activeLang = SUPPORTED_LANGS.includes(lang) ? lang : "bg";
    document.documentElement.lang = activeLang;
    document.title = getTranslation(activeLang, "pageTitle");

    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        el.textContent = getTranslation(activeLang, key);
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        el.setAttribute("placeholder", getTranslation(activeLang, key));
    });

    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
        const key = el.getAttribute("data-i18n-title");
        el.setAttribute("title", getTranslation(activeLang, key));
    });
}